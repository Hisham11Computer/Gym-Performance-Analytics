"""
Generates a reproducible synthetic dataset for the Gym Performance Analytics project.

Usage:  python scripts/generate_seed_data.py
Output: sql/02_seed_data.sql   (+ data/*.csv for quick inspection / Power BI import)

The data is SIMULATED (fixed random seed) - it is not real gym data.
The first 5 members keep the profiles from the original 5-member sample.
"""
import csv
import random
from datetime import date, timedelta
from pathlib import Path

random.seed(2026)

ROOT = Path(__file__).resolve().parent.parent
START = date(2026, 4, 6)          # a Monday
WEEKS = 12
SESSION_DAYS = (0, 2, 4)          # Mon / Wed / Fri
EXERCISES = ["Bench Press", "Squat", "Deadlift", "Overhead Press", "Barbell Row"]
BW_RATIO = {"Bench Press": 0.75, "Squat": 1.0, "Deadlift": 1.2,
            "Overhead Press": 0.45, "Barbell Row": 0.65}
LEVEL_MULT = {"beginner": 0.8, "intermediate": 1.0, "advanced": 1.2}
LEVEL_RATE = {"beginner": 1.3, "intermediate": 1.0, "advanced": 0.6}
GOAL_RATE = {"bulk": 0.022, "cut": 0.010}
GOAL_CAL = {"bulk": 2800, "cut": 2150}

# (name, gender, age, weight_kg, goal) - first five come from the original project
fixed = [("James", "M", 22, 65, "bulk"), ("Liam", "M", 25, 78, "cut"),
         ("Noah", "M", 21, 60, "bulk"), ("Ethan", "M", 27, 85, "cut"),
         ("Lucas", "M", 24, 70, "bulk")]
male = ["Oliver", "Elijah", "William", "Benjamin", "Henry", "Alexander", "Mason", "Michael",
        "Daniel", "Jacob", "Logan", "Jackson", "Levi", "Sebastian", "Mateo", "Jack", "Owen",
        "Theodore", "Aiden", "Samuel", "Joseph", "John", "David", "Wyatt", "Matthew", "Luke",
        "Dylan", "Ryan", "Nathan", "Tyler", "Adam"]
female = ["Emma", "Olivia", "Sophia", "Isabella", "Mia", "Charlotte", "Amelia", "Emily"]

members = []
for i, (n, g, a, w, goal) in enumerate(fixed, 1):
    members.append(dict(id=i, name=n, gender=g, age=a, weight=float(w), goal=goal,
                        level=random.choice(["beginner", "intermediate"])))
rest = [(n, "M") for n in male] + [(n, "F") for n in female]
for n, g in rest:
    members.append(dict(
        id=len(members) + 1, name=n, gender=g, age=random.randint(18, 45),
        weight=round(random.uniform(52, 72) if g == "F" else random.uniform(62, 98), 1),
        goal=random.choice(["bulk", "cut"]),
        level=random.choices(["beginner", "intermediate", "advanced"], [4, 4, 2])[0]))

# members who quit part-way (churn) - useful for the retention analysis
quitters = {m["id"]: random.randint(4, 8) for m in random.sample(members[5:], 7)}

workouts, nutrition = [], []
wid = nid = 1
for m in members:
    mean_cal = random.gauss(GOAL_CAL[m["goal"]], 150)
    cal_effect = 0.00003 * (mean_cal - GOAL_CAL[m["goal"]])
    rate = (GOAL_RATE[m["goal"]] * LEVEL_RATE[m["level"]] + cal_effect
            + random.gauss(0, 0.003))
    rate = max(rate, 0.0)
    attend = random.uniform(0.6, 0.95)
    sex_mult = 0.65 if m["gender"] == "F" else 1.0
    base = {ex: m["weight"] * BW_RATIO[ex] * LEVEL_MULT[m["level"]] * sex_mult
               * random.uniform(0.9, 1.1) for ex in EXERCISES}
    last_week = quitters.get(m["id"], WEEKS)
    slot = 0
    for wk in range(WEEKS):
        for d in SESSION_DAYS:
            ex = EXERCISES[slot % len(EXERCISES)]
            slot += 1
            if wk >= last_week or random.random() > attend:
                continue
            day = START + timedelta(weeks=wk, days=d)
            w = base[ex] * (1 + rate * wk) * random.uniform(0.98, 1.02)
            w = round(round(w / 2.5) * 2.5, 1)
            reps = random.choice([5, 6, 8, 8, 10, 10, 12])
            workouts.append((wid, m["id"], day.isoformat(), ex, w, reps)); wid += 1
            if random.random() < 0.9:
                cal = int(round(random.gauss(mean_cal, 180), -1))
                prot = int(round(m["weight"] * random.uniform(1.6, 2.4)))
                nutrition.append((nid, m["id"], day.isoformat(), cal, prot)); nid += 1


def batch_insert(table, cols, rows, fmt, size=100):
    out = []
    for i in range(0, len(rows), size):
        chunk = rows[i:i + size]
        out.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES")
        out.append(",\n".join("  (" + fmt(r) + ")" for r in chunk) + ";\n")
    return "\n".join(out)


q = lambda s: "'" + str(s).replace("'", "''") + "'"
member_rows = [(m["id"], m["name"], m["gender"], m["age"], m["weight"], m["goal"], m["level"]) for m in members]
sql = ["-- =============================================================",
       "-- 02_seed_data.sql  |  SIMULATED data (generated by scripts/generate_seed_data.py)",
       f"-- {len(members)} members, {len(workouts)} workouts, {len(nutrition)} nutrition logs",
       "-- =============================================================\n",
       batch_insert("Members", ["member_id", "name", "gender", "age", "weight_kg", "goal", "experience_level"],
                    member_rows,
                    lambda r: f"{r[0]}, {q(r[1])}, {q(r[2])}, {r[3]}, {r[4]}, {q(r[5])}, {q(r[6])}"),
       batch_insert("Workouts", ["workout_id", "member_id", "workout_date", "exercise", "weight_lifted", "reps"],
                    workouts, lambda r: f"{r[0]}, {r[1]}, {q(r[2])}, {q(r[3])}, {r[4]}, {r[5]}"),
       batch_insert("Nutrition_Members", ["nutrition_id", "member_id", "log_date", "calories", "protein_g"],
                    nutrition, lambda r: f"{r[0]}, {r[1]}, {q(r[2])}, {r[3]}, {r[4]}")]
(ROOT / "sql" / "02_seed_data.sql").write_text("\n".join(sql), encoding="utf-8")

for name, header, rows in [
    ("members", ["member_id", "name", "gender", "age", "weight_kg", "goal", "experience_level"], member_rows),
    ("workouts", ["workout_id", "member_id", "workout_date", "exercise", "weight_lifted", "reps"], workouts),
    ("nutrition", ["nutrition_id", "member_id", "log_date", "calories", "protein_g"], nutrition)]:
    with open(ROOT / "data" / f"{name}.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f); w.writerow(header); w.writerows(rows)

print(len(members), "members |", len(workouts), "workouts |", len(nutrition), "nutrition logs")
